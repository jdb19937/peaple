def render_text_png(txt, dim):
    """Fallback: plain monospace text (used when the font model server is unavailable)."""
    from PIL import Image, ImageDraw, ImageFont
    scale = max(1, dim // 8)
    try:
        font = ImageFont.truetype('/usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf', 11)
    except OSError:
        font = ImageFont.load_default()
    w = max(8, int(font.getlength(txt)) + 4)
    h = 14
    img = Image.new('RGB', (w, h), (255, 255, 255))
    ImageDraw.Draw(img).text((2, 0), txt, fill=(0, 0, 0), font=font)
    if scale > 1:
        img = img.resize((w * scale, h * scale), Image.NEAREST)
    buf = io.BytesIO()
    img.save(buf, 'PNG')
    return buf.getvalue()


# ---- fontasy: text rendered from a generated font sheet ----
# A sheet holds the 96 printable ASCII glyphs on a 12 x 8 grid of 2u x 3u cells (u = side / 24),
# centered; a phont name seeds the latent exactly like a peaple nom (sha256 chain -> uniform).
import hashlib, struct, socket, threading, time
FONT_HOST = os.environ.get('PEAPLE_FONTHOST', 'localhost:4446')
LLM_HOST = os.environ.get('PEAPLE_LLMHOST', 'localhost:8090')   # llama-server for /<nom>/chat.sse
CHAT_LOG = os.environ.get('PEAPLE_CHATLOG', os.path.expanduser('~/tewel/ffhq.proj/run/chat.jsonl'))   # transcripts, one JSON line per exchange
_sheet_cache = {}
_sheet_lock = threading.Lock()
_inflight = {}                       # nom -> Event, renders in progress (single-flight)
_gpu_sem = threading.Semaphore(1)    # at most one tewel subprocess on the GPU


def nom_vec(nom, n=1536):
    v = []
    sha = nom.encode('utf-8')
    while len(v) < n:
        sha = hashlib.sha256(sha).digest()
        v += [(x + 0.5) / 4294967296.0 for x in struct.unpack('>8I', sha)]
    return v[:n]


STATIC_PHONTS = os.environ.get('PEAPLE_PHONTS', '/home/dan/datasets/fonts/xiterm/sheets384')


# glyph-conditional font model (font2): sheets are rendered by `tewel glyphs`, which decodes the 96
# reference glyphs with one style vector; the nom's first 512 uniforms become a gaussian latent
TEWEL = os.environ.get('TEWEL', '/home/dan/tewel/tewel')
FONT2_DIR = os.environ.get('PEAPLE_FONT2', '/home/dan/tewel/ffhq.proj')
FONT2_MAP = os.path.join(FONT2_DIR, 'font2_map.ctx')
FONT2_GEN = os.path.join(FONT2_DIR, 'font2_gen_ema.ctx')
FONT2_REF = os.environ.get('PEAPLE_FONT2_REF', '/home/dan/datasets/fonts/glyphs/refsheet96.u8')
FONT2_TMP = os.path.join(ROOT, '.font2_tmp')


def font2_available():
    return os.path.isfile(FONT2_MAP) and os.path.isfile(FONT2_GEN) and os.path.isfile(FONT2_REF)


def render_font2_sheet(nom):
    from PIL import Image
    from statistics import NormalDist
    import subprocess, tempfile
    os.makedirs(FONT2_TMP, exist_ok=True)
    nd = NormalDist()
    z = [nd.inv_cdf(min(max(u, 1e-9), 1 - 1e-9)) for u in nom_vec(nom)[:512]]
    fd, zfn = tempfile.mkstemp(prefix='z_', suffix='.dat', dir=FONT2_TMP)
    os.close(fd)
    outfn = zfn[:-4] + '.rgb'
    try:
        with open(zfn, 'wb') as f:
            f.write(struct.pack('<512d', *z))
        subprocess.run([TEWEL, 'glyphs', FONT2_MAP, FONT2_GEN, 'ref=' + FONT2_REF, 'zdat=' + zfn, 'out=' + outfn],
                       check=True, timeout=120, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        with open(outfn, 'rb') as f:
            raw = f.read()
        side = int(round((len(raw) // 3) ** 0.5))
        return Image.frombytes('RGB', (side, side), raw[:side * side * 3]).convert('L')
    finally:
        for fn in (zfn, outfn):
            try: os.unlink(fn)
            except OSError: pass


def fetch_sheet(nom):
    """Return this phont's sheet as a PIL image: a static sheet (ahoy, mork, they, titulus, ...)
    from PEAPLE_PHONTS if one exists, otherwise generated by the font model (font2 glyph model when its
    checkpoints exist, else the font model server), cached 30 s."""
    from PIL import Image
    static = os.path.join(STATIC_PHONTS, nom + '.png')
    if os.path.isfile(static):
        return Image.open(static).convert('RGB')
    with _sheet_lock:
        hit = _sheet_cache.get(nom)
        if hit and time.time() - hit[0] < 30:
            return hit[1]
        ev = _inflight.get(nom)
        if ev is None:
            ev = _inflight[nom] = threading.Event()
            leader = True
        else:
            leader = False
    if not leader:
        # another request is already rendering this phont: wait for it instead of starting a second render
        ev.wait(180)
        with _sheet_lock:
            hit = _sheet_cache.get(nom)
        if hit:
            return hit[1]
        raise RuntimeError('render of %s failed' % nom)
    try:
        if font2_available():
            with _gpu_sem:          # one model process on the GPU at a time; training shares it
                img = render_font2_sheet(nom)
        else:
            img = _fetch_sheet_server(nom)
        with _sheet_lock:
            _sheet_cache[nom] = (time.time(), img)
        return img
    finally:
        with _sheet_lock:
            _inflight.pop(nom, None)
        ev.set()


def _fetch_sheet_server(nom):
    """Sheet from the chain model server (the pre-font2 path)."""
    host, port = FONT_HOST.split(':')
    s = socket.create_connection((host, int(port)), timeout=60)
    s.sendall(struct.pack('<i', 0) + b'\0' * 252 + struct.pack('<1536d', *nom_vec(nom)))
    data = b''
    while b'IEND' not in data:
        chunk = s.recv(65536)
        if not chunk:
            break
        data += chunk
    s.close()
    from PIL import Image
    return Image.open(io.BytesIO(data)).convert('L')


def render_fontasy_grid_png(nom, dim):
    """The whole 12x8 glyph sheet (ASCII 0x20..0x7F row-major), each cell 2dim x 3dim px: the chat page draws
    its transcript from this on a canvas."""
    from PIL import Image
    sheet = fetch_sheet(nom)
    side = sheet.size[0]
    u = side // 24
    o = (side - 24 * u) // 2
    grid = sheet.crop((o, o, o + 24 * u, o + 24 * u)).resize((24 * dim, 24 * dim), Image.LANCZOS)
    buf = io.BytesIO()
    grid.save(buf, 'PNG')
    return buf.getvalue()


def render_mork_strip(txt, scale):
    """Text in the mork phont as a PIL image, 2*scale x 3*scale px per character (the old makemore Mork::print at
    theme mork_<scale>)."""
    from PIL import Image
    sheet = fetch_sheet('mork')
    side = sheet.size[0]
    u = side // 24
    cw, ch = 2 * u, 3 * u
    o = (side - 24 * u) // 2
    strip = Image.new('RGB', (cw * max(1, len(txt)), ch), (0, 0, 0))
    for k, c in enumerate(txt):
        code = ord(c)
        if code < 0x20 or code > 0x7E:
            code = 0x7F
        i = code - 0x20
        strip.paste(sheet.crop((o + (i % 12) * cw, o + (i // 12) * ch, o + (i % 12 + 1) * cw, o + (i // 12 + 1) * ch)), (k * cw, 0))
    return strip.resize((2 * scale * max(1, len(txt)), 3 * scale), Image.NEAREST)   # mork is solid blocks: keep them crisp


def render_text_strip(txt, scale):
    """Small fixed-width text on an opaque black bar for the URL stamp: the X11 4x6 bitmap font (pixel-exact, the same
    4x6 cell as the old mork_2 glyphs at 256), scaled by nearest-neighbour for larger faces.  fonts/4x6.pil was
    converted from /usr/share/fonts/X11/misc/4x6-ISO8859-1.pcf.gz with PIL's PcfFontFile."""
    from PIL import Image, ImageDraw, ImageFont
    font = ImageFont.load(os.path.join(ROOT, 'fonts', '4x6.pil'))
    im = Image.new('RGB', (4 * len(txt) + 2, 6), (0, 0, 0))
    ImageDraw.Draw(im).text((1, 0), txt, fill=(255, 255, 255), font=font)
    k = max(1, scale // 2)
    return im if k == 1 else im.resize((im.width * k, im.height * k), Image.NEAREST)


def stamp_png(png, nom):
    """The old agent.cc stamp (makemore agent.cc ~2899), restored: unless ?nostamp, a face 128 px or larger gets its
    own URL printed in mork along the bottom left and, stacked up the bottom right, the render time as <unix>Z and the
    visage's created and revised ages in seconds.  The old code printed at mork_2 (4x6 px glyphs) on a 256 canvas and
    warped to the requested size; here the glyph scale follows the native size (2x3 at 128, 4x6 at 256) so it looks
    the same on screen.  The old 'thum' theme used for the URL at 256 is not on this machine; mork stands in."""
    from PIL import Image
    im = Image.open(io.BytesIO(png)).convert('RGB')
    w, h = im.size
    if w < 128:
        return png
    scale = max(1, w // 128)
    now = int(time.time())
    url = render_text_strip('https://peaple.io/' + nom, scale)
    im.paste(url, (0, h - url.size[1]))
    # the corner tag: a square of mork, 6 glyphs by 4 rows (24x24 px at 256), reading row by row: the render time as
    # ten digits and 'Z', then the first 13 hex digits of sha256(nom) -- a pseudo-QR of the hash and a timestamp.
    # (the old agent.cc stacked three ragged strips: <unix>Z, created age, revised age)
    tag = '%010dZ' % now + hashlib.sha256(nom.encode()).hexdigest()[:13]
    rows = [render_mork_strip(tag[i:i + 6], scale) for i in range(0, 24, 6)]
    for r, strip in enumerate(rows):
        im.paste(strip, (w - strip.size[0], h - (4 - r) * strip.size[1]))
    buf = io.BytesIO()
    im.save(buf, 'PNG')
    return buf.getvalue()


def render_fontasy_png(nom, txt, dim):
    from PIL import Image
    sheet = fetch_sheet(nom)
    side = sheet.size[0]
    u = side // 24
    cw, ch = 2 * u, 3 * u
    ox0 = oy0 = (side - 24 * u) // 2
    cells = []
    for c in txt:
        code = ord(c)
        if code < 0x20 or code > 0x7E:
            code = 0x7F
        i = code - 0x20
        col, row = i % 12, i // 12
        cells.append(sheet.crop((ox0 + col * cw, oy0 + row * ch, ox0 + (col + 1) * cw, oy0 + (row + 1) * ch)))
    mode = sheet.mode
    if not cells:
        cells = [Image.new(mode, (cw, ch), 255 if mode == 'L' else (255, 255, 255))]
    strip = Image.new(mode, (cw * len(cells), ch), 255 if mode == 'L' else (255, 255, 255))
    for k, cell in enumerate(cells):
        strip.paste(cell, (k * cw, 0))
    # the original fontasy sizes: dim=8 -> 16 x 24 px per character
    strip = strip.resize((2 * dim * len(cells), 3 * dim), Image.LANCZOS)
    buf = io.BytesIO()
    strip.save(buf, 'PNG')
    return buf.getvalue()


def run_cgi(method, path, query='', body=b'', headers=None):
    """Run peaple.pl for one request.  Returns (status, [(header, value)], payload); status 502/504 on a broken run."""
    headers = headers or {}
    env = dict(os.environ)
    env.update({
        'GATEWAY_INTERFACE': 'CGI/1.1',
        'REQUEST_METHOD': method,
        'PATH_INFO': urllib.parse.unquote(path),
        'QUERY_STRING': query,
        'SCRIPT_NAME': '',
        'SERVER_NAME': 'localhost',
        'SERVER_PORT': str(PORT),
        'SERVER_PROTOCOL': 'HTTP/1.1',
        'REMOTE_ADDR': headers.get('X-Peer') or '127.0.0.1',
        'CONTENT_LENGTH': str(len(body)),
        'CONTENT_TYPE': headers.get('Content-Type') or '',
        'HTTP_HOST': headers.get('Host') or 'localhost',
        'HTTP_COOKIE': headers.get('Cookie') or '',
        'HTTP_USER_AGENT': headers.get('User-Agent') or '',
        'HTTP_REFERER': headers.get('Referer') or '',
        'HTTP_CF_CONNECTING_IP': headers.get('CF-Connecting-IP') or '',
    })
    try:
        p = subprocess.run(['perl', SCRIPT], input=body, env=env, cwd=ROOT, capture_output=True, timeout=120)
    except subprocess.TimeoutExpired:
        return 504, [], b'CGI timeout'
    if p.stderr:
        sys.stderr.write(p.stderr.decode('utf-8', 'replace'))
    out = p.stdout
    sep = out.find(b'\r\n\r\n')
    nl = 4
    if sep < 0:
        sep = out.find(b'\n\n')
        nl = 2
    if sep < 0:
        return 502, [], p.stderr[-300:] or b'bad CGI output'
    status, hl = 200, []
    for line in out[:sep].decode('latin-1').splitlines():
        if ':' not in line:
            continue
        k, v = line.split(':', 1)
        k, v = k.strip(), v.strip()
        if k.lower() == 'status':
            status = int(v.split()[0])
        elif k.lower() != 'content-length':
            hl.append((k, v))
    return status, hl, out[sep + nl:]


class Handler(BaseHTTPRequestHandler):
    protocol_version = 'HTTP/1.1'

    def log_message(self, fmt, *args):
        sys.stderr.write("%s %s\n" % (self.command, self.path))
    def log_request(self, code='-', size='-'):
        import accesslog; accesslog.log(self, code)

    def do_GET(self):
        self.dispatch()

    def do_POST(self):
        self.dispatch()

    def dispatch(self):
        url = urllib.parse.urlsplit(self.path)
        if url.path.startswith('/fontasy/') or url.path == '/button.png':
            return self.fontasy(url)
        parts = url.path.strip('/').split('/')
        if url.path == '/mcp':
            return self.mcp()
        m = re.match(r'^/top/(online|activity|likes|likes24)\.json$', url.path)
        if m:
            n = urllib.parse.parse_qs(url.query).get('n', ['256'])[0]
            return self.send_json(social.top_board(m.group(1), int(n) if n.isdigit() else 256), extra=[('Cache-Control', 'no-store')])
        if len(parts) == 2 and parts[1] == 'chat.sse' and self.command == 'POST':
            return self.chat_sse(parts[0])
        if url.path == '/recipes.json':
            return self.send_json(social.op_recipes(), extra=[('Cache-Control', 'no-store')])
        if len(parts) == 2 and parts[1] == 'mix.json':
            # a nom's steering mix: private like thotz, only its own logged-in nom reads or sets it
            me = social.cookie_user(self)
            if not me or me != parts[0]:
                return self.send_json({'ok': False, 'error': 'not your mix'}, 403)
            try:
                if self.command == 'POST':
                    form = urllib.parse.parse_qs(self.rfile.read(min(int(self.headers.get('Content-Length') or 0), 4096)).decode('utf-8', 'replace'), keep_blank_values=True)
                    r = social.op_set_mix(form.get('text', [''])[0], social.make_session(me, 300))
                else:
                    r = dict(social.op_get_mix(social.make_session(me, 300)), ok=True)
            except social.OpError as e:
                r = {'ok': False, 'error': str(e)}
            return self.send_json(r, extra=[('Cache-Control', 'no-store')])
        if len(parts) == 2 and parts[1] == 'persona.txt':
            import importlib, persona; importlib.reload(persona)   # pick up edits without a restart
            # thotz (a nom's own system prompt) is private: only its own logged-in nom gets the real thing here;
            # everyone else, and ?default=1, gets the hashed personality
            dflt = urllib.parse.parse_qs(url.query).get('default') or social.cookie_user(self) != parts[0]
            body = (persona.default_prompt(parts[0]) if dflt else persona.system_prompt(parts[0])).encode('utf-8')
            self.send_response(200); self.send_header('Content-Type', 'text/plain; charset=utf-8')
            self.send_header('Content-Length', str(len(body))); self.end_headers(); self.wfile.write(body)
            return
        self.cgi(url)

    def send_json(self, obj, status=200, extra=()):
        body = json.dumps(obj).encode('utf-8')
        self.send_response(status)
        self.send_header('Content-Type', 'application/json')
        for k, v in extra:
            self.send_header(k, v)
        self.send_header('Content-Length', str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    def chat_sse(self, nom):
        """Stream a parson's reply: the client posts {"messages": [...]} (its own user/assistant history); social.py
        runs the exchange (persona prompt, the visitor's login name from the session cookie, tool calls against the
        site) and this relays spoken text and action lines as OpenAI-style SSE content deltas."""
        import accesslog
        length = int(self.headers.get('Content-Length') or 0)
        try:
            body = json.loads(self.rfile.read(length) or b'{}')
            msgs = social.clean_history(body.get('messages'))
            think = bool(body.get('think'))      # the brane button: the parson thinks first, and the thinking is shown
        except Exception:
            return self.send_error(400, 'bad request')
        if not nom.replace('_', '').isalnum() or len(nom) > 31:
            return self.send_error(400, 'bad nom')
        ip = accesslog.client_ip(self)
        def sse(text, tool=None):
            delta = {'content': text}
            if tool:
                delta['tool'] = tool      # the browser keeps it and sends it back with the history
            self.wfile.write(b'data: ' + json.dumps({'choices': [{'index': 0, 'delta': delta}]}).encode() + b'\n\n')
            self.wfile.flush()
        self.close_connection = True
        self.send_response(200)
        self.send_header('Content-Type', 'text/event-stream')
        self.send_header('Cache-Control', 'no-store')
        self.send_header('X-Accel-Buffering', 'no')
        self.send_header('Connection', 'close')
        self.end_headers()
        try:
            social.chat_admit(ip)
        except social.Busy as e:
            sse('(%s)' % e)
            self.wfile.write(b'data: [DONE]\n\n')
            return
        gen = social.chat_events(nom, msgs, social.cookie_user(self),
                                 {'ip': ip, 'ua': (self.headers.get('User-Agent') or '-')[:200], 'via': 'web'}, think=think)
        try:
            for ev in gen:
                if ev[0] == 'think':      # the model's reasoning: its own delta field, drawn dimmed, never sent back as history
                    self.wfile.write(b'data: ' + json.dumps({'choices': [{'index': 0, 'delta': {'thinking': ev[1]}}]}).encode() + b'\n\n')
                    self.wfile.flush()
                    continue
                sse(ev[1], ev[2] if len(ev) > 2 else None)
            self.wfile.write(b'data: [DONE]\n\n')
            self.wfile.flush()
        except (BrokenPipeError, ConnectionResetError):
            pass
        finally:
            gen.close()

    def mcp(self):
        """The MCP endpoint (Streamable HTTP, stateless): one JSON-RPC message or batch per POST, answered as JSON."""
        import accesslog
        if self.command != 'POST':
            body = b'peaple.io MCP server: POST JSON-RPC here (Streamable HTTP). Tools: ' + \
                   ', '.join(t['name'] for t in social.MCP_TOOLS).encode() + b'\n'
            self.send_response(405); self.send_header('Allow', 'POST'); self.send_header('Content-Type', 'text/plain')
            self.send_header('Content-Length', str(len(body))); self.end_headers(); self.wfile.write(body)
            return
        length = int(self.headers.get('Content-Length') or 0)
        if length > 1 << 20:
            return self.send_error(413, 'too large')
        try:
            req = json.loads(self.rfile.read(length) or b'null')
        except ValueError:
            return self.send_json({'jsonrpc': '2.0', 'id': None, 'error': {'code': -32700, 'message': 'parse error'}}, 400)
        auth = self.headers.get('Authorization') or ''
        bearer = auth[7:].strip() if auth[:7].lower() == 'bearer ' else ''
        ip, ua = accesslog.client_ip(self), (self.headers.get('User-Agent') or '-')[:200]
        if isinstance(req, list):
            out = [r for r in (social.mcp_handle(m, bearer, ip, ua) for m in req[:16]) if r is not None]
        else:
            out = social.mcp_handle(req, bearer, ip, ua)
        if out is None or out == []:
            self.send_response(202); self.send_header('Content-Length', '0'); self.end_headers()
            return
        self.send_json(out)

    def fontasy(self, url):
        q = urllib.parse.parse_qs(url.query)
        txt = q.get('txt', ['?'])[0]
        dim = int(q.get('dim', ['8'])[0] or 8)
        nom = q.get('theme', [None])[0] or os.path.basename(url.path).rsplit('.', 1)[0] or 'phont4'
        try:
            if 'grid' in q:
                png = render_fontasy_grid_png(nom, int(q['grid'][0] or 8))
            else:
                png = render_fontasy_png(nom, txt, dim)
        except Exception as e:
            sys.stderr.write('fontasy: model render failed (%s), using fallback text\n' % e)
            png = render_text_png(txt, dim)
        self.send_response(200)
        self.send_header('Content-Type', 'image/png')
        self.send_header('Content-Length', str(len(png)))
        self.send_header('Cache-Control', 'private, no-store')  # user wants no edge caching: always re-render
        self.end_headers()
        self.wfile.write(png)

    def cgi(self, url):
        length = int(self.headers.get('Content-Length') or 0)
        body = self.rfile.read(length) if length else b''
        hdr = {k: self.headers.get(k) for k in ('Content-Type', 'Host', 'Cookie', 'User-Agent', 'Referer', 'CF-Connecting-IP')}
        hdr['X-Peer'] = self.client_address[0]
        status, headers, payload = run_cgi(self.command, url.path, url.query, body, hdr)
        if status in (502, 504) and not headers:
            return self.send_error(status, 'CGI failed')
        m = re.match(r'^/([a-z0-9_]+)\.png$', url.path)
        if m and status == 200 and payload[:4] == b'\x89PNG':
            social.count_view(m.group(1), self.headers.get('User-Agent'))   # the /top activity board
            if 'nostamp' not in urllib.parse.parse_qs(url.query):
                try:
                    payload = stamp_png(payload, m.group(1))
                except Exception as e:
                    sys.stderr.write('stamp failed: %s\n' % e)
        self.send_response(status)
        for k, v in headers:
            self.send_header(k, v)
        if url.path.endswith('.png') and status == 200 and not any(k.lower() == 'cache-control' for k, _ in headers):
            self.send_header('Cache-Control', 'private, no-store')   # user wants no edge caching
        self.send_header('Content-Length', str(len(payload)))
        self.end_headers()
        self.wfile.write(payload)


# visage store sweep: peaple.pm keeps one 16 KB file per nom under ROOT/visages, touched on every load; bots that crawl
# fam pages create six records per page, so every 10 minutes drop the least recently used beyond the cap
VISAGE_DIR = os.path.join(ROOT, 'visages')
VISAGE_CAP = int(os.environ.get('PEAPLE_VISAGE_CAP', '20000'))

def visage_sweep():
    while True:
        try:
            ents = []
            for d in os.scandir(VISAGE_DIR):
                if not d.is_dir():
                    continue
                for f in os.scandir(d.path):
                    if f.name.endswith('.vis'):
                        ents.append((f.stat().st_mtime, f.path))
                    elif f.name.endswith('.tmp') and time.time() - f.stat().st_mtime > 600:
                        os.remove(f.path)   # abandoned partial write
            if len(ents) > VISAGE_CAP:
                # only generated stubs go: never a record with the keep flag (anything somebody made or changed), a password or a wall
                social.accounts.scan()
                ents.sort()
                over, gone = len(ents) - VISAGE_CAP, 0
                for _, p in ents:
                    if gone >= over:
                        break
                    nom = os.path.basename(p)[:-4]
                    if nom in social.accounts.pinned or social.has_wall(nom) or social.kept(p):
                        continue
                    try:
                        os.remove(p); gone += 1
                    except OSError:
                        pass
                sys.stderr.write('visage sweep: %d records, removed %d\n' % (len(ents), gone))
        except Exception as e:
            sys.stderr.write('visage sweep failed: %s\n' % e)
        time.sleep(600)


if __name__ == '__main__':
    os.makedirs(VISAGE_DIR, exist_ok=True)
    social.init(ROOT, run_cgi, LLM_HOST, CHAT_LOG)
    threading.Thread(target=visage_sweep, daemon=True).start()
    print("peaple dev server on port %d, bind %s  (root %s)" % (PORT, os.environ.get("PEAPLE_BIND", "::"), ROOT))
    bind = os.environ.get('PEAPLE_BIND', '::')
    class DualStackServer(ThreadingHTTPServer):
        address_family = socket.AF_INET6 if ':' in bind else socket.AF_INET
        def server_bind(self):
            if self.address_family == socket.AF_INET6:
                self.socket.setsockopt(socket.IPPROTO_IPV6, socket.IPV6_V6ONLY, 0)
            super().server_bind()
    DualStackServer((bind, PORT), Handler).serve_forever()
