#!/usr/bin/env python3
"""Local development server for peaple.

Runs peaple.pl as a CGI script for every path (as the original Apache setup
did via a root-mounted ScriptAlias), and serves a stand-in for the fontasy.io
text-to-PNG buttons at /fontasy/<anything>.png?txt=...&dim=8.

Usage: devserver.py [port]   (default 8080)
Environment it sets for the CGI: PEAPLE_ROOT, PEAPLE_FONTASY (unless already set).
"""
import os, sys, io, socket, subprocess, urllib.parse
from http.server import ThreadingHTTPServer, BaseHTTPRequestHandler

ROOT = os.path.dirname(os.path.abspath(__file__))
SCRIPT = os.path.join(ROOT, 'peaple.pl')
PORT = int(sys.argv[1]) if len(sys.argv) > 1 else 8080

os.environ.setdefault('PEAPLE_ROOT', ROOT)
os.environ.setdefault('PEAPLE_FONTASY', '/fontasy/')
os.environ.setdefault('PEAPLE_MAXDIM', '128')   # output size of the served generator chain


def render_text_png(txt, dim):
    """Fallback: plain monospace text (used when the font model server is unavailable)."""
    from PIL import Image, ImageDraw, ImageFont
    scale = max(1, dim // 8)
    try:
        font = ImageFont.truetype('/usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf', 11)
    except OSError:
        font = ImageFont.load_default()
    w = max(8, int(font.getlength(txt)) + 4)
    h = 14
    img = Image.new('RGB', (w, h), (255, 255, 255))
    ImageDraw.Draw(img).text((2, 0), txt, fill=(0, 0, 0), font=font)
    if scale > 1:
        img = img.resize((w * scale, h * scale), Image.NEAREST)
    buf = io.BytesIO()
    img.save(buf, 'PNG')
    return buf.getvalue()


# ---- fontasy: text rendered from a generated font sheet ----
# A sheet holds the 96 printable ASCII glyphs on a 12 x 8 grid of 2u x 3u cells (u = side / 24),
# centered; a phont name seeds the latent exactly like a peaple nom (sha256 chain -> uniform).
import hashlib, struct, socket, threading, time
FONT_HOST = os.environ.get('PEAPLE_FONTHOST', 'localhost:4446')
LLM_HOST = os.environ.get('PEAPLE_LLMHOST', 'localhost:8090')   # llama-server for /<nom>/chat.sse
_sheet_cache = {}
_sheet_lock = threading.Lock()
_inflight = {}                       # nom -> Event, renders in progress (single-flight)
_gpu_sem = threading.Semaphore(1)    # at most one tewel subprocess on the GPU


def nom_vec(nom, n=1536):
    v = []
    sha = nom.encode('utf-8')
    while len(v) < n:
        sha = hashlib.sha256(sha).digest()
        v += [(x + 0.5) / 4294967296.0 for x in struct.unpack('>8I', sha)]
    return v[:n]


STATIC_PHONTS = os.environ.get('PEAPLE_PHONTS', '/home/dan/datasets/fonts/xiterm/sheets384')


# glyph-conditional font model (font2): sheets are rendered by `tewel glyphs`, which decodes the 96
# reference glyphs with one style vector; the nom's first 512 uniforms become a gaussian latent
TEWEL = os.environ.get('TEWEL', '/home/dan/tewel/tewel')
FONT2_DIR = os.environ.get('PEAPLE_FONT2', '/home/dan/tewel/ffhq.proj')
FONT2_MAP = os.path.join(FONT2_DIR, 'font2_map.ctx')
FONT2_GEN = os.path.join(FONT2_DIR, 'font2_gen_ema.ctx')
FONT2_REF = os.environ.get('PEAPLE_FONT2_REF', '/home/dan/datasets/fonts/glyphs/refsheet96.u8')
FONT2_TMP = os.path.join(ROOT, '.font2_tmp')


def font2_available():
    return os.path.isfile(FONT2_MAP) and os.path.isfile(FONT2_GEN) and os.path.isfile(FONT2_REF)


def render_font2_sheet(nom):
    from PIL import Image
    from statistics import NormalDist
    import subprocess, tempfile
    os.makedirs(FONT2_TMP, exist_ok=True)
    nd = NormalDist()
    z = [nd.inv_cdf(min(max(u, 1e-9), 1 - 1e-9)) for u in nom_vec(nom)[:512]]
    fd, zfn = tempfile.mkstemp(prefix='z_', suffix='.dat', dir=FONT2_TMP)
    os.close(fd)
    outfn = zfn[:-4] + '.rgb'
    try:
        with open(zfn, 'wb') as f:
            f.write(struct.pack('<512d', *z))
        subprocess.run([TEWEL, 'glyphs', FONT2_MAP, FONT2_GEN, 'ref=' + FONT2_REF, 'zdat=' + zfn, 'out=' + outfn],
                       check=True, timeout=120, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        with open(outfn, 'rb') as f:
            raw = f.read()
        side = int(round((len(raw) // 3) ** 0.5))
        return Image.frombytes('RGB', (side, side), raw[:side * side * 3]).convert('L')
    finally:
        for fn in (zfn, outfn):
            try: os.unlink(fn)
            except OSError: pass


def fetch_sheet(nom):
    """Return this phont's sheet as a PIL image: a static sheet (ahoy, mork, they, titulus, ...)
    from PEAPLE_PHONTS if one exists, otherwise generated by the font model (font2 glyph model when its
    checkpoints exist, else the font model server), cached 30 s."""
    from PIL import Image
    static = os.path.join(STATIC_PHONTS, nom + '.png')
    if os.path.isfile(static):
        return Image.open(static).convert('RGB')
    with _sheet_lock:
        hit = _sheet_cache.get(nom)
        if hit and time.time() - hit[0] < 30:
            return hit[1]
        ev = _inflight.get(nom)
        if ev is None:
            ev = _inflight[nom] = threading.Event()
            leader = True
        else:
            leader = False
    if not leader:
        # another request is already rendering this phont: wait for it instead of starting a second render
        ev.wait(180)
        with _sheet_lock:
            hit = _sheet_cache.get(nom)
        if hit:
            return hit[1]
        raise RuntimeError('render of %s failed' % nom)
    try:
        if font2_available():
            with _gpu_sem:          # one model process on the GPU at a time; training shares it
                img = render_font2_sheet(nom)
        else:
            img = _fetch_sheet_server(nom)
        with _sheet_lock:
            _sheet_cache[nom] = (time.time(), img)
        return img
    finally:
        with _sheet_lock:
            _inflight.pop(nom, None)
        ev.set()


def _fetch_sheet_server(nom):
    """Sheet from the chain model server (the pre-font2 path)."""
    host, port = FONT_HOST.split(':')
    s = socket.create_connection((host, int(port)), timeout=60)
    s.sendall(struct.pack('<i', 0) + b'\0' * 252 + struct.pack('<1536d', *nom_vec(nom)))
    data = b''
    while b'IEND' not in data:
        chunk = s.recv(65536)
        if not chunk:
            break
        data += chunk
    s.close()
    from PIL import Image
    return Image.open(io.BytesIO(data)).convert('L')


def render_fontasy_grid_png(nom, dim):
    """The whole 12x8 glyph sheet (ASCII 0x20..0x7F row-major), each cell 2dim x 3dim px: the chat page draws
    its transcript from this on a canvas."""
    from PIL import Image
    sheet = fetch_sheet(nom)
    side = sheet.size[0]
    u = side // 24
    o = (side - 24 * u) // 2
    grid = sheet.crop((o, o, o + 24 * u, o + 24 * u)).resize((24 * dim, 24 * dim), Image.LANCZOS)
    buf = io.BytesIO()
    grid.save(buf, 'PNG')
    return buf.getvalue()


def render_fontasy_png(nom, txt, dim):
    from PIL import Image
    sheet = fetch_sheet(nom)
    side = sheet.size[0]
    u = side // 24
    cw, ch = 2 * u, 3 * u
    ox0 = oy0 = (side - 24 * u) // 2
    cells = []
    for c in txt:
        code = ord(c)
        if code < 0x20 or code > 0x7E:
            code = 0x7F
        i = code - 0x20
        col, row = i % 12, i // 12
        cells.append(sheet.crop((ox0 + col * cw, oy0 + row * ch, ox0 + (col + 1) * cw, oy0 + (row + 1) * ch)))
    mode = sheet.mode
    if not cells:
        cells = [Image.new(mode, (cw, ch), 255 if mode == 'L' else (255, 255, 255))]
    strip = Image.new(mode, (cw * len(cells), ch), 255 if mode == 'L' else (255, 255, 255))
    for k, cell in enumerate(cells):
        strip.paste(cell, (k * cw, 0))
    # the original fontasy sizes: dim=8 -> 16 x 24 px per character
    strip = strip.resize((2 * dim * len(cells), 3 * dim), Image.LANCZOS)
    buf = io.BytesIO()
    strip.save(buf, 'PNG')
    return buf.getvalue()


class Handler(BaseHTTPRequestHandler):
    protocol_version = 'HTTP/1.1'

    def log_message(self, fmt, *args):
        sys.stderr.write("%s %s\n" % (self.command, self.path))
    def log_request(self, code='-', size='-'):
        import accesslog; accesslog.log(self, code)

    def do_GET(self):
        self.dispatch()

    def do_POST(self):
        self.dispatch()

    def dispatch(self):
        url = urllib.parse.urlsplit(self.path)
        if url.path.startswith('/fontasy/') or url.path == '/button.png':
            return self.fontasy(url)
        parts = url.path.strip('/').split('/')
        if len(parts) == 2 and parts[1] == 'chat.sse' and self.command == 'POST':
            return self.chat_sse(parts[0])
        if len(parts) == 2 and parts[1] == 'persona.txt':
            import persona
            body = persona.system_prompt(parts[0]).encode('utf-8')
            self.send_response(200); self.send_header('Content-Type', 'text/plain; charset=utf-8')
            self.send_header('Content-Length', str(len(body))); self.end_headers(); self.wfile.write(body)
            return
        self.cgi(url)

    def chat_sse(self, nom):
        """Stream a parson's reply: the client posts {"messages": [...]} (its own user/assistant history), the parson's
        deterministic persona becomes the system prompt, and llama-server's SSE chunks are relayed as they arrive."""
        import json, http.client, persona
        length = int(self.headers.get('Content-Length') or 0)
        try:
            req = json.loads(self.rfile.read(length) or b'{}')
            msgs = [{'role': m['role'], 'content': m['content'][:2000]} for m in req.get('messages', [])
                    if m.get('role') in ('user', 'assistant') and isinstance(m.get('content'), str)][-24:]
        except Exception:
            return self.send_error(400, 'bad request')
        if not nom.replace('_', '').isalnum():
            return self.send_error(400, 'bad nom')
        payload = json.dumps({'messages': [{'role': 'system', 'content': persona.system_prompt(nom)}] + msgs,
                              'stream': True, 'max_tokens': 220, 'temperature': 0.9,
                              'chat_template_kwargs': {'enable_thinking': False}})
        host, port = LLM_HOST.split(':')
        try:
            conn = http.client.HTTPConnection(host, int(port), timeout=600)
            conn.request('POST', '/v1/chat/completions', payload, {'Content-Type': 'application/json'})
            r = conn.getresponse()
        except Exception as e:
            sys.stderr.write('chat: llm unavailable (%s)\n' % e)
            return self.send_error(503, 'the parson is asleep')
        if r.status != 200:
            sys.stderr.write('chat: llm status %d %s\n' % (r.status, r.read()[:200]))
            return self.send_error(502, 'the parson is confused')
        self.close_connection = True
        self.send_response(200)
        self.send_header('Content-Type', 'text/event-stream')
        self.send_header('Cache-Control', 'no-store')
        self.send_header('X-Accel-Buffering', 'no')
        self.send_header('Connection', 'close')
        self.end_headers()
        try:
            while True:
                line = r.readline()
                if not line:
                    break
                self.wfile.write(line)
                self.wfile.flush()
        except (BrokenPipeError, ConnectionResetError):
            pass
        finally:
            conn.close()

    def fontasy(self, url):
        q = urllib.parse.parse_qs(url.query)
        txt = q.get('txt', ['?'])[0]
        dim = int(q.get('dim', ['8'])[0] or 8)
        nom = q.get('theme', [None])[0] or os.path.basename(url.path).rsplit('.', 1)[0] or 'phont4'
        try:
            if 'grid' in q:
                png = render_fontasy_grid_png(nom, int(q['grid'][0] or 8))
            else:
                png = render_fontasy_png(nom, txt, dim)
        except Exception as e:
            sys.stderr.write('fontasy: model render failed (%s), using fallback text\n' % e)
            png = render_text_png(txt, dim)
        self.send_response(200)
        self.send_header('Content-Type', 'image/png')
        self.send_header('Content-Length', str(len(png)))
        self.send_header('Cache-Control', 'private, no-store')  # user wants no edge caching: always re-render
        self.end_headers()
        self.wfile.write(png)

    def cgi(self, url):
        length = int(self.headers.get('Content-Length') or 0)
        body = self.rfile.read(length) if length else b''
        env = dict(os.environ)
        env.update({
            'GATEWAY_INTERFACE': 'CGI/1.1',
            'REQUEST_METHOD': self.command,
            'PATH_INFO': urllib.parse.unquote(url.path),
            'QUERY_STRING': url.query,
            'SCRIPT_NAME': '',
            'SERVER_NAME': 'localhost',
            'SERVER_PORT': str(PORT),
            'SERVER_PROTOCOL': 'HTTP/1.1',
            'REMOTE_ADDR': self.client_address[0],
            'CONTENT_LENGTH': str(length),
            'CONTENT_TYPE': self.headers.get('Content-Type') or '',
            'HTTP_HOST': self.headers.get('Host') or 'localhost',
            'HTTP_COOKIE': self.headers.get('Cookie') or '',
        })
        try:
            p = subprocess.run(['perl', SCRIPT], input=body, env=env, cwd=ROOT,
                               capture_output=True, timeout=120)
        except subprocess.TimeoutExpired:
            return self.send_error(504, 'CGI timeout')
        if p.stderr:
            sys.stderr.write(p.stderr.decode('utf-8', 'replace'))
        out = p.stdout
        sep = out.find(b'\r\n\r\n')
        nl = 4
        if sep < 0:
            sep = out.find(b'\n\n')
            nl = 2
        if sep < 0:
            return self.send_error(502, 'bad CGI output (exit %d)' % p.returncode)
        hdrs, payload = out[:sep], out[sep + nl:]
        status = 200
        headers = []
        for line in hdrs.decode('latin-1').splitlines():
            if ':' not in line:
                continue
            k, v = line.split(':', 1)
            k, v = k.strip(), v.strip()
            if k.lower() == 'status':
                status = int(v.split()[0])
            elif k.lower() == 'content-length':
                continue
            else:
                headers.append((k, v))
        self.send_response(status)
        for k, v in headers:
            self.send_header(k, v)
        if url.path.endswith('.png') and status == 200 and not any(k.lower() == 'cache-control' for k, _ in headers):
            # faces are deterministic per URL now; a few minutes at Cloudflare's edge keeps reload storms off the GPU
            self.send_header('Cache-Control', 'private, no-store')
        self.send_header('Content-Length', str(len(payload)))
        self.end_headers()
        self.wfile.write(payload)


# visage store sweep: peaple.pm keeps one 16 KB file per nom under ROOT/visages, touched on every load; bots that crawl
# fam pages create six records per page, so every 10 minutes drop the least recently used beyond the cap
VISAGE_DIR = os.path.join(ROOT, 'visages')
VISAGE_CAP = int(os.environ.get('PEAPLE_VISAGE_CAP', '20000'))

def visage_sweep():
    while True:
        try:
            ents = []
            for d in os.scandir(VISAGE_DIR):
                if not d.is_dir():
                    continue
                for f in os.scandir(d.path):
                    if f.name.endswith('.vis'):
                        ents.append((f.stat().st_mtime, f.path))
                    elif f.name.endswith('.tmp') and time.time() - f.stat().st_mtime > 600:
                        os.remove(f.path)   # abandoned partial write
            if len(ents) > VISAGE_CAP:
                ents.sort()
                for _, p in ents[:len(ents) - VISAGE_CAP]:
                    try:
                        os.remove(p)
                    except OSError:
                        pass
                sys.stderr.write('visage sweep: %d records, removed %d\n' % (len(ents), len(ents) - VISAGE_CAP))
        except Exception as e:
            sys.stderr.write('visage sweep failed: %s\n' % e)
        time.sleep(600)


if __name__ == '__main__':
    os.makedirs(VISAGE_DIR, exist_ok=True)
    threading.Thread(target=visage_sweep, daemon=True).start()
    print("peaple dev server on port %d, bind %s  (root %s)" % (PORT, os.environ.get("PEAPLE_BIND", "::"), ROOT))
    bind = os.environ.get('PEAPLE_BIND', '::')
    class DualStackServer(ThreadingHTTPServer):
        address_family = socket.AF_INET6 if ':' in bind else socket.AF_INET
        def server_bind(self):
            if self.address_family == socket.AF_INET6:
                self.socket.setsockopt(socket.IPPROTO_IPV6, socket.IPV6_V6ONLY, 0)
            super().server_bind()
    DualStackServer((bind, PORT), Handler).serve_forever()
